"""P03.18 Verification & Validation: starter code.

Code verification, solution verification and validation of a one-dimensional transient heat-conduction
solver (theta-method in time, central differences in space, Thomas tridiagonal solver), on the problem of
a strip-heated aluminium bar clamped to heat sinks at both ends:

    u_t = alpha u_xx - beta u + q(x, t),   u(0, t) = g0(t),   u(L, t) = gL(t),   u(x, 0) = u0(x),

where u is the temperature rise above ambient [K], alpha the thermal diffusivity [m^2/s], beta a linear
loss coefficient [1/s] (convection to the surroundings, hP/(rho c A)) and q the volumetric heating rate
divided by rho c [K/s].

Verification tools written from scratch: the method of manufactured solutions (SymPy builds the source
term for any chosen exact solution), the discrete L2 error, the observed order of convergence from
successive refinements, Richardson extrapolation with the grid convergence index (GCI), the backward error
of the linear solve, and planted bugs that the order test must catch. Validation tools: a comparison of
the model with *synthetic* thermocouple data carrying a stated uncertainty, a validation metric that
combines numerical and experimental uncertainty, and a one-parameter calibration of the loss coefficient.

Conventions:
    * Grids are uniform with nx intervals (nx + 1 nodes); the unknowns are the nx - 1 interior values.
    * theta = 0.5 is Crank-Nicolson (second order in time), theta = 1 is backward Euler (first order).
    * Tridiagonal systems are stored as three length-n arrays (lower, diag, upper): row i reads
      lower[i] x[i-1] + diag[i] x[i] + upper[i] x[i+1] = rhs[i]; lower[0] and upper[-1] are ignored.
    * In the Richardson routine f1 is the finest-grid value, f3 the coarsest (NPARC convention).
    * All "measurements" in this lesson are synthetic: generated by a model with a term the solver under
      test omits, plus seeded Gaussian noise, and labelled as such in every output.

Given: ``HeatSetup``, ``tridiagonal_matvec``, ``heater_source``, ``separable_solution``,
``sample_solution``, ``synthetic_measurements`` and ``main``; everything else is yours.

Run:  python main.py          (prints the verification and validation tables, writes heat_vv.png)
Test: pytest curriculum/phase-03/lesson-18-verification-and-validation
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

import numpy as np


# ---------------------------------------------------------------- the physical problem (GIVEN)


@dataclass(frozen=True)
class HeatSetup:
    """A 10 mm square aluminium bar, 0.5 m long, clamped to heat sinks at ambient temperature at both ends
    and heated by a strip heater centred at x0. ``beta_true`` is the convective loss coefficient
    h P / (rho c A) of the "true" bar that generates the synthetic data; the model under test omits it
    unless told otherwise. All values are plausible textbook numbers, not measurements."""

    L: float = 0.5                 # bar length [m]
    alpha: float = 9.75e-5         # thermal diffusivity of aluminium, k/(rho c) = 237/(2700*900) [m^2/s]
    beta_true: float = 8.2e-4      # h P/(rho c A) for h = 5 W/(m^2 K), 10 mm square section [1/s]
    Q: float = 0.5                 # peak heating rate / (rho c) [K/s]
    x0: float = 0.2                # heater centre [m]
    w: float = 0.03                # heater Gaussian half-width [m]
    t_end: float = 600.0           # duration of the experiment [s]
    x_sensors: tuple = (0.1, 0.2, 0.3, 0.4)            # thermocouple positions [m]
    t_sensors: tuple = (100.0, 200.0, 300.0, 400.0, 500.0, 600.0)   # sampling times [s]
    sigma_meas: float = 0.3        # thermocouple standard uncertainty [K]


def tridiagonal_matvec(lower: np.ndarray, diag: np.ndarray, upper: np.ndarray, x: np.ndarray) -> np.ndarray:
    """A x for the tridiagonal matrix stored as (lower, diag, upper)."""
    y = diag * x
    y[1:] += lower[1:] * x[:-1]
    y[:-1] += upper[:-1] * x[1:]
    return y


def heater_source(p: HeatSetup) -> Callable[[np.ndarray, float], np.ndarray]:
    """q(x, t) [K/s]: a Gaussian strip heater switched on at t = 0."""
    def q(x, t):
        x = np.asarray(x, dtype=float)
        return p.Q * np.exp(-0.5 * ((x - p.x0) / p.w) ** 2) * np.ones_like(x)
    return q


def separable_solution(x: np.ndarray, t: float, alpha: float, L: float, T0: float = 1.0, beta: float = 0.0) -> np.ndarray:
    """Exact solution u = T0 sin(pi x/L) exp(-(alpha (pi/L)^2 + beta) t) of the homogeneous problem with
    zero Dirichlet ends (an analytical solution of physical significance)."""
    return T0 * np.sin(np.pi * np.asarray(x) / L) * math.exp(-(alpha * (math.pi / L) ** 2 + beta) * t)


def sample_solution(x: np.ndarray, t: np.ndarray, U: np.ndarray, x_s, t_s) -> np.ndarray:
    """Values of the solution history U (shape (len(t), len(x))) at sensor positions x_s and times t_s;
    linear interpolation in x, nearest time step in t (the caller chooses nt so the times align).
    Returns shape (len(t_s), len(x_s))."""
    out = np.empty((len(t_s), len(x_s)))
    for i, ts in enumerate(t_s):
        k = int(np.argmin(np.abs(np.asarray(t) - ts)))
        out[i] = np.interp(np.asarray(x_s), x, U[k])
    return out


def synthetic_measurements(p: HeatSetup, seed: int = 18, nx: int = 400) -> dict:
    """SYNTHETIC thermocouple data: the truth model includes the convective loss beta_true, is solved on a
    fine grid, sampled at the sensors and perturbed by Gaussian noise of standard deviation sigma_meas.
    The returned dict carries the label ``"source": "synthetic"``; nothing here was measured."""
    x = np.linspace(0.0, p.L, nx + 1)
    nt = int(round(p.t_end / 0.5))                       # dt = 0.5 s so every sensor time is a step
    U = heat_theta(x, np.zeros_like(x), p.t_end, nt, p.alpha, beta=p.beta_true, source=heater_source(p))
    t = np.linspace(0.0, p.t_end, nt + 1)
    truth = sample_solution(x, t, U, p.x_sensors, p.t_sensors)
    rng = np.random.default_rng(seed)
    data = truth + p.sigma_meas * rng.standard_normal(truth.shape)
    return {"source": "synthetic", "x": np.asarray(p.x_sensors), "t": np.asarray(p.t_sensors),
            "data": data, "u_data": np.full(truth.shape, p.sigma_meas), "truth": truth, "seed": seed}


# ---------------------------------------------------------------- the linear solver


def thomas_solve(lower: np.ndarray, diag: np.ndarray, upper: np.ndarray, rhs: np.ndarray) -> np.ndarray:
    """Solve the tridiagonal system (lower, diag, upper) x = rhs by the Thomas algorithm (Gaussian
    elimination without pivoting, O(n)). Raises ValueError on a zero pivot. Backward stable for
    diagonally dominant matrices, which the theta-method matrices always are."""
    raise NotImplementedError


def backward_error(lower, diag, upper, x, rhs) -> float:
    """Normwise relative backward error ||A x - b||_inf / (||A||_inf ||x||_inf + ||b||_inf): the size of the
    smallest relative perturbation of the data for which x is the exact solution. A backward-stable solver
    returns a few units of machine epsilon however ill-conditioned A is (18.335J, Lecture 3); the forward
    error is then at most the condition number times that."""
    raise NotImplementedError


# ---------------------------------------------------------------- the PDE solver


def _source_values(q, x, t):
    v = np.asarray(q(x, t), dtype=float)
    return np.broadcast_to(v, x.shape)


def heat_theta(x: np.ndarray, u0: np.ndarray, t_end: float, nt: int, alpha: float, beta: float = 0.0,
               source=None, bc=None, theta: float = 0.5, bug: str | None = None) -> np.ndarray:
    """theta-method / central-difference solution of u_t = alpha u_xx - beta u + q with Dirichlet ends.

    x: uniform grid (nx + 1 nodes); u0: initial values on x; nt time steps of dt = t_end/nt;
    source: q(x_array, t) -> array (None means zero); bc: (g0, gL) callables of t (None means zero);
    theta: 0.5 Crank-Nicolson, 1.0 backward Euler.
    bug: None, or one of the planted bugs used in the lesson's verification exercise:
        "source_time"  evaluates the source at t_n instead of the theta-weighted level (drops the time
                       order of Crank-Nicolson to one);
        "diffusivity"  uses 1.02 alpha (converges, to the wrong answer).
    Returns the history U with shape (nt + 1, nx + 1); U[k] is the solution at t = k dt.
    """
    raise NotImplementedError


# ---------------------------------------------------------------- verification tools


def manufactured_source(u_expr, x_sym, t_sym, alpha: float, beta: float = 0.0):
    """Method of manufactured solutions: for a chosen exact solution u(x, t) given as a SymPy expression in
    the symbols (x_sym, t_sym), return (u_fn, q_fn) with q = u_t - alpha u_xx + beta u, both callables
    (x_array, t) -> array. The boundary and initial data come from u_fn itself."""
    raise NotImplementedError


def l2_error(u_num: np.ndarray, u_exact: np.ndarray, dx: float) -> float:
    """Discrete L2 norm of the error, sqrt(dx sum (u - u_e)^2): the grid analogue of the L2 norm, so that
    values on different grids are comparable."""
    raise NotImplementedError


def observed_order(errors, r: float = 2.0) -> np.ndarray:
    """Observed orders p_k = log(e_k / e_{k+1}) / log(r) from a sequence of errors on grids refined by the
    constant factor r (finest last)."""
    raise NotImplementedError


def convergence_study(run, n_list) -> np.ndarray:
    """Call run(n) for every resolution in n_list and return the array of errors it reports."""
    raise NotImplementedError


def richardson(f1: float, f2: float, f3: float, r: float = 2.0, Fs: float = 1.25, p_formal: float | None = None) -> dict:
    """Grid-convergence analysis of a functional computed on three grids with constant refinement ratio r:
    f1 finest, f2 medium, f3 coarsest. Returns the observed order p = ln((f3 - f2)/(f2 - f1))/ln r, the
    Richardson-extrapolated value f1 + (f1 - f2)/(r^p - 1), the relative changes eps21 = (f2 - f1)/f1 and
    eps32 = (f3 - f2)/f2, the grid convergence indices GCI = Fs |eps| / (r^p - 1) of the fine and medium
    grids (Fs = 1.25 for three or more grids), and the asymptotic-range ratio GCI32 / (r^p GCI21).
    When ``p_formal`` (the scheme's formal order) is given, the extrapolation, the GCIs and the ratio use
    it instead of the observed order; the ratio is then a genuine test of the asymptotic range (equal to 1
    only when the observed and formal orders agree), whereas with the observed order it is f1/f2 by
    construction. Raises ValueError when the differences are zero or of opposite sign (oscillatory
    convergence; the formulas do not apply)."""
    raise NotImplementedError


def required_refinement(gci_fine: float, p: float, target: float) -> float:
    """Factor by which the fine grid must be refined for its GCI to fall to ``target``: (gci/target)^(1/p)."""
    raise NotImplementedError


# ---------------------------------------------------------------- validation tools


def validation_comparison(model: np.ndarray, data: np.ndarray, u_data: np.ndarray, u_num: float | np.ndarray) -> dict:
    """Validation metric: comparison error E = model - data, validation uncertainty
    u_val = sqrt(u_data^2 + u_num^2), the normalised error E/u_val, the count of points within 2 u_val, and
    the reduced chi-square sum((E/u_val)^2)/N. A model whose |E| exceeds 2 u_val at many points has a
    model-form error larger than the uncertainties can explain; one with reduced chi-square near 1 is
    validated *at the level of u_val* (which says nothing about its being right elsewhere)."""
    raise NotImplementedError


def fit_loss_coefficient(run_model: Callable[[float], np.ndarray], data: np.ndarray, u_data: np.ndarray,
                         bracket=(0.0, 5e-3)) -> dict:
    """Calibrate the loss coefficient beta by minimising chi^2 = sum((run_model(beta) - data)^2 / u_data^2)
    over the bracket (bounded scalar minimisation, scipy). Returns beta, chi^2 at the optimum and the
    number of model evaluations. Calibration absorbs whatever disagreement a single parameter can absorb;
    it is not validation, and the calibrated model must be checked on data it was not fitted to."""
    raise NotImplementedError


# ---------------------------------------------------------------- driver (GIVEN)


def _mms_case(p: HeatSetup):
    import sympy as sp
    xs, ts = sp.symbols("x t")
    tau = 200.0
    u_expr = 40 * sp.sin(sp.pi * xs / p.L) * (1 - sp.exp(-ts / tau)) + 10 * sp.sin(2 * sp.pi * xs / p.L) * sp.exp(-ts / tau)
    return manufactured_source(u_expr, xs, ts, p.alpha)


def main(fig_path: str | Path = "heat_vv.png") -> dict:
    """Verification and validation of the heat solver on the strip-heated bar. Writes heat_vv.png."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    p = HeatSetup()
    out: dict = {}

    # ---- code verification 1: exact discrete solution (polynomial), constant solution, linear solver
    x = np.linspace(0.0, p.L, 41)
    u_poly = lambda xx, t: 2.0 * t * xx * (p.L - xx)
    q_poly = lambda xx, t: 2.0 * xx * (p.L - xx) + 4.0 * p.alpha * t
    U = heat_theta(x, u_poly(x, 0.0), 100.0, 10, p.alpha, source=q_poly)
    out["poly_err"] = float(np.max(np.abs(U[-1] - u_poly(x, 100.0))))
    rng = np.random.default_rng(18)
    n = 300
    lower, upper = rng.standard_normal(n), rng.standard_normal(n)
    diag = np.abs(lower) + np.abs(upper) + 1.0 + rng.random(n)
    b = rng.standard_normal(n)
    sol = thomas_solve(lower, diag, upper, b)
    out["backward_error"] = backward_error(lower, diag, upper, sol, b)
    print(f"exact discrete (polynomial) solution reproduced to {out['poly_err']:.1e} K; "
          f"Thomas backward error {out['backward_error']:.1e} (machine epsilon {np.finfo(float).eps:.1e})")

    # ---- code verification 2: manufactured solution, observed order, planted bugs
    u_m, q_m = _mms_case(p)
    t_end = 300.0

    def run(nx, theta=0.5, bug=None):
        xg = np.linspace(0.0, p.L, nx + 1)
        Ug = heat_theta(xg, u_m(xg, 0.0), t_end, nx, p.alpha, source=q_m, theta=theta, bug=bug)
        return l2_error(Ug[-1], u_m(xg, t_end), xg[1] - xg[0])

    n_list = [25, 50, 100, 200, 400]
    err = convergence_study(run, n_list)
    ordr = observed_order(err)
    out["mms_errors"], out["mms_orders"] = err, ordr
    print("manufactured solution, Crank-Nicolson, dt = t_end/nx:")
    for nn, e in zip(n_list, err):
        print(f"  nx = {nn:4d}: L2 error {e:.3e} K")
    print(f"  observed orders {np.array2string(ordr, precision=3)}")
    err_bug = convergence_study(lambda nn: run(nn, bug="source_time"), n_list)
    err_alpha = convergence_study(lambda nn: run(nn, bug="diffusivity"), n_list)
    err_be = convergence_study(lambda nn: run(nn, theta=1.0), n_list)
    out["bug_orders"] = observed_order(err_bug)
    out["alpha_orders"] = observed_order(err_alpha)
    out["be_orders"] = observed_order(err_be)
    print(f"  planted bug 'source_time': errors {np.array2string(err_bug, precision=2)}, orders {np.array2string(out['bug_orders'], precision=2)}")
    print(f"  planted bug 'diffusivity': errors {np.array2string(err_alpha, precision=2)}, orders {np.array2string(out['alpha_orders'], precision=2)}")
    print(f"  backward Euler (theta = 1):  errors {np.array2string(err_be, precision=2)}, orders {np.array2string(out['be_orders'], precision=2)}")

    # ---- solution verification: Richardson extrapolation and GCI of two functionals
    def heater_run(nx, beta=0.0):
        xg = np.linspace(0.0, p.L, nx + 1)
        return heat_theta(xg, np.zeros_like(xg), p.t_end, nx, p.alpha, beta=beta, source=heater_source(p))[-1]

    def at_heater(nx):                                   # temperature rise at x = x0 (a node of every grid)
        return float(heater_run(nx)[int(round(nx * p.x0 / p.L))])

    def peak(nx):                                        # maximum over the nodes: not a smooth functional
        return float(np.max(heater_run(nx)))

    f3, f2, f1 = at_heater(25), at_heater(50), at_heater(100)
    rich = richardson(f1, f2, f3)
    f_ref = at_heater(800)
    out["richardson"] = rich
    out["point_values"] = (f3, f2, f1, f_ref)
    print(f"temperature rise at the heater, t = {p.t_end:.0f} s: nx = 25/50/100 -> {f3:.4f}/{f2:.4f}/{f1:.4f} K; "
          f"observed p = {rich['p']:.3f}, Richardson {rich['f_extrap']:.4f} K (nx = 800 gives {f_ref:.4f}), "
          f"GCI_fine = {100 * rich['gci_fine']:.4f} %, actual |f1 - f_ref|/f1 = {100 * abs(f1 - f_ref) / f1:.4f} %, "
          f"asymptotic ratio with p = 2: {richardson(f1, f2, f3, p_formal=2.0)['asymptotic_ratio']:.3f}")
    print(f"  refinement of the fine grid for GCI 0.01 %: factor {required_refinement(rich['gci_fine'], rich['p'], 1e-4):.2f}")
    g3, g2, g1 = peak(25), peak(50), peak(100)
    rich_max = richardson(g1, g2, g3)
    out["richardson_max"] = rich_max
    print(f"  the same with the nodal maximum: {g3:.4f}/{g2:.4f}/{g1:.4f} K -> observed p = {rich_max['p']:.2f}, "
          f"asymptotic ratio with p = 2: {richardson(g1, g2, g3, p_formal=2.0)['asymptotic_ratio']:.1f} (not asymptotic: the node under the peak moves)")

    # ---- validation against SYNTHETIC thermocouple data
    meas = synthetic_measurements(p)
    nx_v = 200
    xv = np.linspace(0.0, p.L, nx_v + 1)
    ntv = int(round(p.t_end / 1.0))
    tv = np.linspace(0.0, p.t_end, ntv + 1)

    def model(beta):
        Uv = heat_theta(xv, np.zeros_like(xv), p.t_end, ntv, p.alpha, beta=beta, source=heater_source(p))
        return sample_solution(xv, tv, Uv, p.x_sensors, p.t_sensors)

    u_num = rich["gci_fine"] * f1                        # numerical uncertainty from the GCI [K]
    m0 = model(0.0)
    v0 = validation_comparison(m0, meas["data"], meas["u_data"], u_num)
    fit = fit_loss_coefficient(model, meas["data"], meas["u_data"])
    m1 = model(fit["beta"])
    v1 = validation_comparison(m1, meas["data"], meas["u_data"], u_num)
    out.update({"v_no_loss": v0, "fit": fit, "v_fit": v1, "meas": meas})
    print(f"validation against SYNTHETIC data (seed {meas['seed']}, {meas['data'].size} points, u_data = {p.sigma_meas} K, u_num = {u_num:.3f} K):")
    print(f"  model without loss: {v0['n_within_2']}/{v0['n_total']} points within 2 u_val, reduced chi2 {v0['chi2_reduced']:.1f}, "
          f"max |E|/u_val {v0['max_abs_z']:.1f}, worst E = {np.max(np.abs(v0['E'])):.2f} K")
    print(f"  calibrated beta = {fit['beta']:.3e} 1/s (truth {p.beta_true:.3e}, {fit['n_eval']} model runs): "
          f"{v1['n_within_2']}/{v1['n_total']} within 2 u_val, reduced chi2 {v1['chi2_reduced']:.2f}")

    # ---- figure
    fig, ax = plt.subplots(1, 3, figsize=(13, 4))
    ax[0].loglog(n_list, err, "o-", label="Crank-Nicolson")
    ax[0].loglog(n_list, err_bug, "s--", label="bug: source at $t_n$")
    ax[0].loglog(n_list, err_alpha, "d:", label=r"bug: 1.02 $\alpha$")
    ax[0].loglog(n_list, err[0] * (n_list[0] / np.asarray(n_list, float)) ** 2, "k-", lw=0.8, label="slope 2")
    ax[0].set_xlabel("nx"); ax[0].set_ylabel("discrete L2 error [K]"); ax[0].legend(fontsize=8)
    ax[0].set_title("code verification: manufactured solution")
    ax[1].plot(xv, heat_theta(xv, np.zeros_like(xv), p.t_end, ntv, p.alpha, source=heater_source(p))[-1], label=r"model, $\beta = 0$")
    ax[1].plot(xv, heat_theta(xv, np.zeros_like(xv), p.t_end, ntv, p.alpha, beta=fit["beta"], source=heater_source(p))[-1], label=r"calibrated $\beta$")
    ax[1].errorbar(meas["x"], meas["data"][-1], yerr=2 * meas["u_data"][-1], fmt="k.", capsize=3, label="synthetic data, t = 600 s")
    ax[1].set_xlabel("x [m]"); ax[1].set_ylabel("temperature rise [K]"); ax[1].legend(fontsize=8)
    ax[1].set_title("validation (synthetic data)")
    for j, xs_ in enumerate(p.x_sensors):
        ax[2].plot(meas["t"], v0["z"][:, j], "o-", label=f"x = {xs_} m")
    ax[2].axhspan(-2, 2, color="0.9")
    ax[2].set_xlabel("t [s]"); ax[2].set_ylabel(r"$E / u_{val}$ (model without loss)"); ax[2].legend(fontsize=8)
    ax[2].set_title("comparison error")
    fig.tight_layout()
    fig.savefig(fig_path, dpi=120)
    plt.close(fig)
    return out


if __name__ == "__main__":
    main()
