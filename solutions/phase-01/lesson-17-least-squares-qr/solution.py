"""P01.17 Orthogonality, Least Squares & QR: reference solution.

Fit a parabolic drag polar C_D = C_D0 + K C_L**2 to (simulated) wind-tunnel data by least squares,
with Gram-Schmidt QR written from scratch and ``numpy.linalg.qr`` / ``numpy.linalg.lstsq`` as the oracle.

Conventions:
    * A is the m x n design matrix (m measurements, n parameters, m > n), b the measurement vector,
      x the parameter vector. The least-squares solution minimises |A x - b|_2.
    * QR here is the *reduced* factorisation: Q is m x n with orthonormal columns, R is n x n upper
      triangular with positive diagonal, A = Q R.
    * The wind-tunnel data are generated by this module (``wind_tunnel_data``) from a known polar plus
      Gaussian noise. They are a simulation of a measurement, not a measurement.

Run:  python solution.py          (prints the fit, writes drag_polar_fit.png)
Test: AEFS_IMPL=solution pytest curriculum/phase-01/lesson-17-least-squares-qr
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

# "True" polar used to simulate the tunnel: a clean wing of aspect ratio 8 at low Mach.
TRUE_CD0 = 0.025          # zero-lift drag coefficient
TRUE_E = 0.85             # Oswald span-efficiency factor
ASPECT_RATIO = 8.0
TRUE_K = 1.0 / (np.pi * TRUE_E * ASPECT_RATIO)   # induced-drag factor, 0.04684
CL_ALPHA_PER_DEG = 0.095  # lift-curve slope (per degree), about 5.44 per radian
ALPHA_ZERO_LIFT = -2.0    # degrees


def wind_tunnel_data(seed: int = 17, n_points: int = 17, noise_cl: float = 0.005,
                     noise_cd: float = 0.0008) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return (alpha_deg, C_L, C_D) for a simulated alpha sweep from -4 to 12 degrees.

    C_L = CL_ALPHA_PER_DEG (alpha - ALPHA_ZERO_LIFT) + noise, C_D = TRUE_CD0 + TRUE_K C_L_clean**2 + noise,
    with independent Gaussian noise of the given standard deviations (``numpy.random.default_rng(seed)``).
    ``noise_cl = noise_cd = 0`` gives the exact polar.
    """
    rng = np.random.default_rng(seed)
    alpha = np.linspace(-4.0, 12.0, n_points)
    cl_clean = CL_ALPHA_PER_DEG * (alpha - ALPHA_ZERO_LIFT)
    cd_clean = TRUE_CD0 + TRUE_K * cl_clean ** 2
    cl = cl_clean + noise_cl * rng.standard_normal(n_points)
    cd = cd_clean + noise_cd * rng.standard_normal(n_points)
    return alpha, cl, cd


# ---------------------------------------------------------------- orthogonalisation

def classical_gram_schmidt(A: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Return the reduced QR factorisation of a full-column-rank m x n matrix by classical Gram-Schmidt.

    Column j of Q is a_j minus its projections onto *the original* q_0 .. q_{j-1}, all computed from a_j,
    then normalised; R holds the projection coefficients and the norms. Raise ``ValueError`` if m < n
    or a column is (numerically) dependent on the previous ones.
    """
    A = np.asarray(A, dtype=float)
    m, n = A.shape
    if m < n:
        raise ValueError("need at least as many rows as columns")
    Q = np.zeros((m, n))
    R = np.zeros((n, n))
    for j in range(n):
        v = A[:, j].copy()
        for i in range(j):
            R[i, j] = Q[:, i] @ A[:, j]            # coefficient from the ORIGINAL column
            v -= R[i, j] * Q[:, i]
        R[j, j] = np.linalg.norm(v)
        if R[j, j] <= 1e-13 * max(1.0, np.linalg.norm(A[:, j])):
            raise ValueError(f"column {j} is linearly dependent on the previous columns")
        Q[:, j] = v / R[j, j]
    return Q, R


def modified_gram_schmidt(A: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Return the reduced QR factorisation by modified Gram-Schmidt.

    Same arithmetic as the classical version except that each projection coefficient is computed from the
    *partially orthogonalised* vector, which keeps Q orthogonal to rounding even when A is ill-conditioned.
    Same errors as ``classical_gram_schmidt``.
    """
    A = np.asarray(A, dtype=float)
    m, n = A.shape
    if m < n:
        raise ValueError("need at least as many rows as columns")
    Q = np.zeros((m, n))
    R = np.zeros((n, n))
    for j in range(n):
        v = A[:, j].copy()
        for i in range(j):
            R[i, j] = Q[:, i] @ v                  # coefficient from the CURRENT remainder
            v -= R[i, j] * Q[:, i]
        R[j, j] = np.linalg.norm(v)
        if R[j, j] <= 1e-13 * max(1.0, np.linalg.norm(A[:, j])):
            raise ValueError(f"column {j} is linearly dependent on the previous columns")
        Q[:, j] = v / R[j, j]
    return Q, R


def orthogonality_loss(Q: np.ndarray) -> float:
    """Return max |Q^T Q - I|: how far the columns of Q are from orthonormal."""
    Q = np.asarray(Q, dtype=float)
    return float(np.max(np.abs(Q.T @ Q - np.eye(Q.shape[1]))))


def back_substitution(R: np.ndarray, y: np.ndarray) -> np.ndarray:
    """Solve R x = y for upper-triangular R by back substitution. Raise ``ValueError`` on a zero diagonal entry."""
    R = np.asarray(R, dtype=float)
    y = np.asarray(y, dtype=float)
    n = R.shape[0]
    if np.any(np.diag(R) == 0.0):
        raise ValueError("R is singular: zero on the diagonal")
    x = np.zeros(n)
    for i in range(n - 1, -1, -1):
        x[i] = (y[i] - R[i, i + 1:] @ x[i + 1:]) / R[i, i]
    return x


# ---------------------------------------------------------------- projections and least squares

def projection_matrix(A: np.ndarray) -> np.ndarray:
    """Return P = Q Q^T, the orthogonal projector onto the column space of A (= A (A^T A)^{-1} A^T)."""
    Q, _ = modified_gram_schmidt(A)
    return Q @ Q.T


def least_squares_normal(A: np.ndarray, b: np.ndarray) -> np.ndarray:
    """Solve the normal equations (A^T A) x = A^T b with ``numpy.linalg.solve``.

    Mathematically exact; numerically it squares the condition number of A (see the lesson).
    """
    A = np.asarray(A, dtype=float)
    b = np.asarray(b, dtype=float)
    return np.linalg.solve(A.T @ A, A.T @ b)


def least_squares_qr(A: np.ndarray, b: np.ndarray, explicit_qtb: bool = False) -> np.ndarray:
    """Solve the least-squares problem via A = Q R from modified Gram-Schmidt: R x = Q^T b by back substitution.

    By default Q^T b is formed the way R was, by orthogonalising b against q_0, q_1, ... one at a time with the
    running remainder (b treated as an extra column), which keeps the method backward stable. With
    ``explicit_qtb=True`` the product ``Q.T @ b`` is used instead; the two agree for a well-conditioned A, but
    for an ill-conditioned one the explicit product inherits the loss of orthogonality of Q (see the lesson).
    """
    A = np.asarray(A, dtype=float)
    b = np.asarray(b, dtype=float)
    Q, R = modified_gram_schmidt(A)
    if explicit_qtb:
        return back_substitution(R, Q.T @ b)
    v = b.copy()
    c = np.zeros(A.shape[1])
    for i in range(A.shape[1]):
        c[i] = Q[:, i] @ v
        v -= c[i] * Q[:, i]
    return back_substitution(R, c)


def residual_orthogonality(A: np.ndarray, b: np.ndarray, x: np.ndarray) -> float:
    """Return max |A^T (b - A x)|: zero (to rounding) exactly when x is the least-squares solution."""
    A = np.asarray(A, dtype=float)
    r = np.asarray(b, dtype=float) - A @ np.asarray(x, dtype=float)
    return float(np.max(np.abs(A.T @ r)))


def parameter_standard_errors(A: np.ndarray, residuals: np.ndarray) -> np.ndarray:
    """Return the standard error of each fitted parameter: sqrt(diag(s^2 (A^T A)^{-1})), s^2 = r^T r / (m - n).

    Assumes independent measurement errors of equal variance (estimated from the residuals). Uses the QR
    factors: (A^T A)^{-1} = R^{-1} R^{-T}. Raise ``ValueError`` if m <= n.
    """
    A = np.asarray(A, dtype=float)
    r = np.asarray(residuals, dtype=float)
    m, n = A.shape
    if m <= n:
        raise ValueError("no degrees of freedom left to estimate the noise")
    s2 = r @ r / (m - n)
    _, R = modified_gram_schmidt(A)
    R_inv = np.column_stack([back_substitution(R, e) for e in np.eye(n)])
    cov = s2 * R_inv @ R_inv.T
    return np.sqrt(np.diag(cov))


# ---------------------------------------------------------------- the drag polar

def design_matrix(cl: np.ndarray, model: str = "parabolic") -> np.ndarray:
    """Return the design matrix for the drag polar.

    ``"parabolic"``: columns [1, C_L**2] for C_D = C_D0 + K C_L**2.
    ``"general"``:   columns [1, C_L, C_L**2] for a polar whose minimum drag is not at zero lift.
    Raise ``ValueError`` for any other model name.
    """
    cl = np.asarray(cl, dtype=float)
    if model == "parabolic":
        return np.column_stack([np.ones_like(cl), cl ** 2])
    if model == "general":
        return np.column_stack([np.ones_like(cl), cl, cl ** 2])
    raise ValueError(f"unknown model {model!r}")


def fit_drag_polar(cl: np.ndarray, cd: np.ndarray) -> dict[str, float | np.ndarray]:
    """Fit C_D = C_D0 + K C_L**2 by QR least squares.

    Returns a dict with ``cd0``, ``k``, their standard errors ``cd0_se`` and ``k_se``, the residual vector
    ``residuals`` (measured minus fitted) and its root-mean-square ``rms``. Raise ``ValueError`` if fewer than
    three points are given.
    """
    cl = np.asarray(cl, dtype=float)
    cd = np.asarray(cd, dtype=float)
    if cl.shape != cd.shape or cl.size < 3:
        raise ValueError("need at least three (C_L, C_D) pairs of matching shape")
    A = design_matrix(cl, "parabolic")
    x = least_squares_qr(A, cd)
    r = cd - A @ x
    se = parameter_standard_errors(A, r)
    return {"cd0": float(x[0]), "k": float(x[1]), "cd0_se": float(se[0]), "k_se": float(se[1]),
            "residuals": r, "rms": float(np.sqrt(np.mean(r ** 2)))}


def oswald_efficiency(k: float, aspect_ratio: float) -> float:
    """Return e = 1 / (pi AR K) from the fitted induced-drag factor. Raise ``ValueError`` if k or AR is not positive."""
    if k <= 0.0 or aspect_ratio <= 0.0:
        raise ValueError("k and aspect ratio must be positive")
    return 1.0 / (np.pi * aspect_ratio * k)


def max_lift_to_drag(cd0: float, k: float) -> tuple[float, float]:
    """Return ((L/D)_max, C_L at (L/D)_max) = (1 / (2 sqrt(cd0 k)), sqrt(cd0 / k)) for the parabolic polar."""
    if cd0 <= 0.0 or k <= 0.0:
        raise ValueError("cd0 and k must be positive")
    return 1.0 / (2.0 * np.sqrt(cd0 * k)), np.sqrt(cd0 / k)


# ---------------------------------------------------------------- experiments

def monte_carlo_k_scatter(n_trials: int = 400, seed: int = 1700, noise_cl: float = 0.005) -> tuple[float, float]:
    """Return (sample std of fitted K over ``n_trials`` noise realisations, mean of the fit's own K standard error).

    Each trial regenerates the tunnel data with a fresh seed (C_D noise 0.0008, C_L noise ``noise_cl``) and fits
    the polar. The standard-error formula assumes the regressor C_L is exact; with ``noise_cl = 0`` the two numbers
    agree to within the sampling scatter of a few hundred trials, and with C_L noise the sample std is larger.
    """
    rng = np.random.default_rng(seed)
    ks, ses = [], []
    for _ in range(n_trials):
        _, cl, cd = wind_tunnel_data(seed=int(rng.integers(1 << 31)), noise_cl=noise_cl)
        fit = fit_drag_polar(cl, cd)
        ks.append(fit["k"])
        ses.append(fit["k_se"])
    return float(np.std(ks, ddof=1)), float(np.mean(ses))


def condition_squaring(A: np.ndarray) -> tuple[float, float]:
    """Return (cond(A), cond(A^T A)) from ``numpy.linalg.cond``. The second is the square of the first."""
    A = np.asarray(A, dtype=float)
    return float(np.linalg.cond(A)), float(np.linalg.cond(A.T @ A))


def laeuchli_matrix(eps: float, n: int = 3) -> tuple[np.ndarray, np.ndarray]:
    """Return (A, b) for the Laeuchli least-squares problem: A = [ones(n); eps * I_n], b = A @ ones(n).

    The exact least-squares solution is x = ones(n). cond(A) is about sqrt(n) / eps, so for eps below 1e-8 the
    matrix A^T A = ones + eps**2 I rounds to the singular all-ones matrix in float64 while A itself is fine.
    """
    if eps <= 0.0:
        raise ValueError("eps must be positive")
    A = np.vstack([np.ones(n), eps * np.eye(n)])
    return A, A @ np.ones(n)


def laeuchli_comparison(eps: float) -> dict[str, float]:
    """Solve the Laeuchli problem by the normal equations, by MGS-QR (both ways) and by ``numpy.linalg.lstsq``.

    Returns ``cond_A``, ``cond_AtA`` and the max absolute error of each solver against the exact x = ones:
    ``err_normal``, ``err_qr_explicit`` (Q.T @ b formed explicitly), ``err_qr`` (b orthogonalised as an extra
    column) and ``err_lstsq``. A normal-equation solve that raises ``LinAlgError`` (singular A^T A in floating
    point) is reported as ``err_normal = inf``.
    """
    A, b = laeuchli_matrix(eps)
    exact = np.ones(A.shape[1])
    cond_a, cond_ata = condition_squaring(A)
    try:
        err_normal = float(np.max(np.abs(least_squares_normal(A, b) - exact)))
    except np.linalg.LinAlgError:
        err_normal = float("inf")
    return {"cond_A": cond_a, "cond_AtA": cond_ata, "err_normal": err_normal,
            "err_qr_explicit": float(np.max(np.abs(least_squares_qr(A, b, explicit_qtb=True) - exact))),
            "err_qr": float(np.max(np.abs(least_squares_qr(A, b) - exact))),
            "err_lstsq": float(np.max(np.abs(np.linalg.lstsq(A, b, rcond=None)[0] - exact)))}


def main(out_dir: str | Path = ".") -> None:
    """Fit the simulated tunnel data, compare solvers, run the conditioning and Monte Carlo experiments, plot."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out_dir = Path(out_dir)
    alpha, cl, cd = wind_tunnel_data()
    A = design_matrix(cl)
    x_normal = least_squares_normal(A, cd)
    x_qr = least_squares_qr(A, cd)
    x_np = np.linalg.lstsq(A, cd, rcond=None)[0]
    print("simulated tunnel data: 17 points, alpha -4..12 deg, noise sigma_CL = 0.005, sigma_CD = 0.0008")
    print(f"true polar:       C_D0 = {TRUE_CD0:.5f}, K = {TRUE_K:.5f}, e = {TRUE_E:.3f}")
    print(f"normal equations: C_D0 = {x_normal[0]:.5f}, K = {x_normal[1]:.5f}")
    print(f"QR (MGS):         C_D0 = {x_qr[0]:.5f}, K = {x_qr[1]:.5f}")
    print(f"numpy lstsq:      C_D0 = {x_np[0]:.5f}, K = {x_np[1]:.5f}")
    print(f"max |normal - lstsq| = {np.max(np.abs(x_normal - x_np)):.1e}, max |QR - lstsq| = {np.max(np.abs(x_qr - x_np)):.1e}")
    print(f"residual orthogonality max |A^T r| = {residual_orthogonality(A, cd, x_qr):.1e}")
    fit = fit_drag_polar(cl, cd)
    e = oswald_efficiency(fit["k"], ASPECT_RATIO)
    ld_max, cl_ld = max_lift_to_drag(fit["cd0"], fit["k"])
    print(f"\nfit: C_D0 = {fit['cd0']:.5f} +/- {fit['cd0_se']:.5f},  K = {fit['k']:.5f} +/- {fit['k_se']:.5f},"
          f"  rms residual = {fit['rms']:.2e}")
    print(f"     Oswald e = {e:.3f} (true {TRUE_E}),  (L/D)max = {ld_max:.2f} at C_L = {cl_ld:.3f}"
          f"  (true {max_lift_to_drag(TRUE_CD0, TRUE_K)[0]:.2f} at {max_lift_to_drag(TRUE_CD0, TRUE_K)[1]:.3f})")
    P = projection_matrix(A)
    print(f"projector: max|P^2 - P| = {np.max(np.abs(P @ P - P)):.1e}, trace = {np.trace(P):.6f} (= number of parameters)")

    print("\nGram-Schmidt on a near-dependent 3-column matrix (Laeuchli form, eps = 1e-8):")
    eps = 1e-8
    L = np.vstack([np.ones(3), eps * np.eye(3)])
    for name, fn in (("classical", classical_gram_schmidt), ("modified", modified_gram_schmidt)):
        Q, R = fn(L)
        print(f"  {name:9s}: loss of orthogonality max|Q^T Q - I| = {orthogonality_loss(Q):.1e}, "
              f"max|A - QR| = {np.max(np.abs(L - Q @ R)):.1e}")
    Qn, _ = np.linalg.qr(L)
    print(f"  numpy.linalg.qr (Householder): {orthogonality_loss(Qn):.1e}")

    print("\nLaeuchli problem: the normal equations square the condition number")
    print("     eps     cond(A)     cond(A^T A)   err normal   err QR explicit Q^T b   err QR   err lstsq")
    for eps in (1e-3, 1e-5, 1e-7, 1e-8):
        r = laeuchli_comparison(eps)
        print(f"  {eps:6.0e}   {r['cond_A']:9.1e}   {r['cond_AtA']:9.1e}   {r['err_normal']:9.1e}   "
              f"{r['err_qr_explicit']:12.1e}          {r['err_qr']:9.1e}   {r['err_lstsq']:9.1e}")
    c_a, c_ata = condition_squaring(A)
    print(f"drag-polar design matrix: cond(A) = {c_a:.2f}, cond(A^T A) = {c_ata:.2f} = cond(A)^2: harmless here")

    for noise_cl in (0.0, 0.005):
        sd_k, se_k = monte_carlo_k_scatter(noise_cl=noise_cl)
        print(f"Monte Carlo, 400 realisations, C_L noise {noise_cl}: std of fitted K = {sd_k:.5f};"
              f" mean formula standard error = {se_k:.5f}")

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(9.5, 3.8))
    cl_line = np.linspace(min(cl.min(), -0.2), cl.max() * 1.05, 200)
    ax1.plot(cd, cl, "o", ms=4, label="simulated tunnel points")
    ax1.plot(fit["cd0"] + fit["k"] * cl_line ** 2, cl_line, "-", label="least-squares parabola")
    ax1.plot(TRUE_CD0 + TRUE_K * cl_line ** 2, cl_line, ":", label="true polar")
    ax1.set_xlabel("$C_D$")
    ax1.set_ylabel("$C_L$")
    ax1.set_title("Drag polar fit")
    ax1.grid(True, lw=0.4)
    ax1.legend(fontsize=8)
    ax2.axhline(0.0, color="gray", lw=0.8)
    ax2.plot(cl, fit["residuals"] * 1e4, "o", ms=4)
    ax2.set_xlabel("$C_L$")
    ax2.set_ylabel(r"residual $\times 10^4$")
    ax2.set_title(f"residuals, rms = {fit['rms'] * 1e4:.2f} x 1e-4")
    ax2.grid(True, lw=0.4)
    fig.tight_layout()
    fig.savefig(out_dir / "drag_polar_fit.png", dpi=150)
    print(f"saved {out_dir / 'drag_polar_fit.png'}")


if __name__ == "__main__":
    main()
