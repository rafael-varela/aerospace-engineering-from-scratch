"""P02.15 Probability Fundamentals: reference solution.

Sample spaces, events and the rules of probability, written as code and checked two ways: by
exact counting (enumeration of equally likely outcomes, binomial coefficients) and by Monte Carlo
simulation with a seeded generator. The lesson's build goes from dice to dispersion: a parachute
payload drifting through ``n`` wind layers, each pushing it a fixed distance east or west and north
or south with equal probability, lands on a grid whose exact distribution is a product of binomial
distributions, and a Monte Carlo run must agree with it to within the standard error.

All wind data in this module are SYNTHETIC: they are generated by the coin-flip model described in
the lesson, not measured.

Conventions:
    * Probabilities are floats in [0, 1]; counts are exact Python integers.
    * Every random function takes ``seed`` and builds ``numpy.random.default_rng(seed)`` itself.
    * A Monte Carlo estimate is returned as ``(p_hat, standard_error)``.

Run:  python solution.py          (prints the tables, writes probability_fundamentals.png)
Test: AEFS_IMPL=solution pytest curriculum/phase-02/lesson-15-probability-fundamentals
"""
from __future__ import annotations

import itertools
import math
from collections.abc import Callable, Sequence
from pathlib import Path

import numpy as np

# ---------------------------------------------------------------- counting

def n_choose_k(n: int, k: int) -> int:
    """Return the binomial coefficient C(n, k) = n! / (k! (n-k)!) as an exact integer.

    Computed by the multiplicative formula C(n, k) = prod_{i=1..k} (n - k + i) / i, which never
    forms a large factorial. Returns 0 when k < 0 or k > n. Raise ``ValueError`` for n < 0.
    """
    if n < 0:
        raise ValueError("n must be non-negative")
    if k < 0 or k > n:
        return 0
    k = min(k, n - k)
    result = 1
    for i in range(1, k + 1):
        result = result * (n - k + i) // i
    return result


def permutations_count(n: int, k: int) -> int:
    """Return P(n, k) = n! / (n-k)!, the number of ordered selections of k items from n."""
    if n < 0 or k < 0:
        raise ValueError("n and k must be non-negative")
    if k > n:
        return 0
    result = 1
    for i in range(n - k + 1, n + 1):
        result *= i
    return result


def enumerate_dice(n_dice: int, sides: int = 6) -> np.ndarray:
    """Return every equally likely outcome of rolling ``n_dice`` dice, shape (sides**n_dice, n_dice).

    This is the sample space written out. Faces are 1..sides.
    """
    if n_dice < 1 or sides < 1:
        raise ValueError("need at least one die with at least one side")
    return np.array(list(itertools.product(range(1, sides + 1), repeat=n_dice)), dtype=int)


def event_probability(outcomes: np.ndarray, predicate: Callable[[np.ndarray], np.ndarray]) -> float:
    """Return the classical probability of an event: (outcomes in the event) / (all outcomes).

    ``predicate`` takes the whole outcome array and returns a boolean array, one entry per outcome.
    Valid only when the outcomes are equally likely.
    """
    mask = np.asarray(predicate(outcomes), dtype=bool)
    if mask.shape != (outcomes.shape[0],):
        raise ValueError("predicate must return one boolean per outcome")
    return float(np.count_nonzero(mask)) / outcomes.shape[0]


def dice_sum_pmf(n_dice: int, sides: int = 6) -> tuple[np.ndarray, np.ndarray]:
    """Return (sums, probabilities) for the total of ``n_dice`` fair dice, by exact counting.

    The count of ways to reach each total is built by convolving the single-die count vector
    (all ones) with itself ``n_dice`` times; dividing by sides**n_dice gives the probabilities.
    """
    if n_dice < 1 or sides < 1:
        raise ValueError("need at least one die with at least one side")
    counts = np.ones(sides, dtype=float)
    total = np.ones(sides, dtype=float)
    for _ in range(n_dice - 1):
        total = np.convolve(total, counts)
    sums = np.arange(n_dice, n_dice * sides + 1)
    return sums, total / sides ** n_dice


# ---------------------------------------------------------------- the rules

def complement(p: float) -> float:
    """Return P(not A) = 1 - P(A). Raise ``ValueError`` outside [0, 1]."""
    if not 0.0 <= p <= 1.0:
        raise ValueError("a probability must lie in [0, 1]")
    return 1.0 - p


def addition_rule(p_a: float, p_b: float, p_ab: float) -> float:
    """Return P(A or B) = P(A) + P(B) - P(A and B)."""
    for p in (p_a, p_b, p_ab):
        if not 0.0 <= p <= 1.0:
            raise ValueError("a probability must lie in [0, 1]")
    if p_ab > min(p_a, p_b) + 1e-15:
        raise ValueError("P(A and B) cannot exceed P(A) or P(B)")
    return p_a + p_b - p_ab


def conditional_probability(p_ab: float, p_b: float) -> float:
    """Return P(A | B) = P(A and B) / P(B). Raise ``ValueError`` if P(B) = 0."""
    if p_b <= 0.0:
        raise ValueError("conditioning on an event of probability zero is undefined")
    if p_ab > p_b + 1e-15:
        raise ValueError("P(A and B) cannot exceed P(B)")
    return p_ab / p_b


def are_independent(p_a: float, p_b: float, p_ab: float, tol: float = 1e-12) -> bool:
    """Return True if P(A and B) = P(A) P(B) to within ``tol``."""
    return abs(p_ab - p_a * p_b) <= tol


def total_probability(priors: Sequence[float], likelihoods: Sequence[float]) -> float:
    """Return P(B) = sum_i P(B | A_i) P(A_i) for a partition A_1..A_m.

    ``priors`` must sum to 1 (a partition); each likelihood is P(B | A_i).
    """
    priors = np.asarray(priors, dtype=float)
    lik = np.asarray(likelihoods, dtype=float)
    if priors.shape != lik.shape:
        raise ValueError("priors and likelihoods must have the same length")
    if abs(priors.sum() - 1.0) > 1e-9 or np.any(priors < 0.0):
        raise ValueError("priors must be a probability distribution over a partition")
    if np.any((lik < 0.0) | (lik > 1.0)):
        raise ValueError("likelihoods must lie in [0, 1]")
    return float(np.dot(priors, lik))


def bayes_posterior(priors: Sequence[float], likelihoods: Sequence[float]) -> np.ndarray:
    """Return the posterior P(A_i | B) = P(B | A_i) P(A_i) / P(B) for every branch of a partition.

    The denominator is ``total_probability``; the posteriors sum to 1. Raise ``ValueError`` if
    P(B) = 0 (the event cannot occur under any branch).
    """
    priors = np.asarray(priors, dtype=float)
    lik = np.asarray(likelihoods, dtype=float)
    p_b = total_probability(priors, lik)
    if p_b <= 0.0:
        raise ValueError("P(B) = 0: cannot condition on an impossible event")
    return priors * lik / p_b


def inspection_tree(prior_defect: float, detection_prob: float, false_alarm_prob: float) -> dict[str, float]:
    """Return the four joint probabilities and the two posteriors of an inspection tree diagram.

    A part is defective with probability ``prior_defect``. The inspection flags a defective part
    with probability ``detection_prob`` and flags a good part with probability ``false_alarm_prob``.
    Keys: 'defect_and_flag', 'defect_and_pass', 'good_and_flag', 'good_and_pass', 'p_flag',
    'p_defect_given_flag', 'p_defect_given_pass'.
    """
    for p in (prior_defect, detection_prob, false_alarm_prob):
        if not 0.0 <= p <= 1.0:
            raise ValueError("a probability must lie in [0, 1]")
    d_f = prior_defect * detection_prob
    d_p = prior_defect * (1.0 - detection_prob)
    g_f = (1.0 - prior_defect) * false_alarm_prob
    g_p = (1.0 - prior_defect) * (1.0 - false_alarm_prob)
    p_flag = d_f + g_f
    p_pass = d_p + g_p
    return {
        "defect_and_flag": d_f, "defect_and_pass": d_p,
        "good_and_flag": g_f, "good_and_pass": g_p,
        "p_flag": p_flag,
        "p_defect_given_flag": d_f / p_flag if p_flag > 0.0 else float("nan"),
        "p_defect_given_pass": d_p / p_pass if p_pass > 0.0 else float("nan"),
    }


# ---------------------------------------------------------------- reliability from the rules

def series_reliability(ps: Sequence[float]) -> float:
    """Return the probability that every one of independent components with reliabilities ``ps`` works."""
    ps = np.asarray(ps, dtype=float)
    if np.any((ps < 0.0) | (ps > 1.0)):
        raise ValueError("reliabilities must lie in [0, 1]")
    return float(np.prod(ps))


def parallel_reliability(ps: Sequence[float]) -> float:
    """Return the probability that at least one of independent components with reliabilities ``ps`` works."""
    ps = np.asarray(ps, dtype=float)
    if np.any((ps < 0.0) | (ps > 1.0)):
        raise ValueError("reliabilities must lie in [0, 1]")
    return 1.0 - float(np.prod(1.0 - ps))


def binomial_probability(k: int, n: int, p: float) -> float:
    """Return P(exactly k successes in n independent trials) = C(n, k) p^k (1-p)^(n-k), by counting."""
    if not 0.0 <= p <= 1.0:
        raise ValueError("p must lie in [0, 1]")
    if k < 0 or k > n:
        return 0.0
    return n_choose_k(n, k) * p ** k * (1.0 - p) ** (n - k)


def k_of_n_reliability(n: int, k: int, p: float) -> float:
    """Return the probability that at least ``k`` of ``n`` identical independent components work.

    Sum of the binomial probabilities for j = k..n. k = 1 is the parallel system, k = n the series one.
    """
    if k < 1 or k > n:
        raise ValueError("need 1 <= k <= n")
    return float(sum(binomial_probability(j, n, p) for j in range(k, n + 1)))


# ---------------------------------------------------------------- Monte Carlo

def proportion_standard_error(p_hat: float, n: int) -> float:
    """Return sqrt(p (1-p) / n), the standard error of a proportion estimated from n trials."""
    if n < 1:
        raise ValueError("need at least one trial")
    return math.sqrt(max(p_hat * (1.0 - p_hat), 0.0) / n)


def monte_carlo_probability(sampler: Callable[[np.random.Generator, int], np.ndarray],
                            event: Callable[[np.ndarray], np.ndarray],
                            n_trials: int, seed: int = 0) -> tuple[float, float]:
    """Estimate P(event) by simulation: return (p_hat, standard_error).

    ``sampler(rng, n)`` draws n outcomes (any array whose first axis indexes trials);
    ``event(outcomes)`` returns a boolean per trial. p_hat is the fraction of trials in the event and
    the standard error is sqrt(p_hat (1 - p_hat) / n).
    """
    if n_trials < 1:
        raise ValueError("need at least one trial")
    rng = np.random.default_rng(seed)
    outcomes = sampler(rng, n_trials)
    hits = np.asarray(event(outcomes), dtype=bool)
    if hits.shape != (n_trials,):
        raise ValueError("event must return one boolean per trial")
    p_hat = float(np.count_nonzero(hits)) / n_trials
    return p_hat, proportion_standard_error(p_hat, n_trials)


def monte_carlo_dice_sum(n_dice: int, target: int, n_trials: int, seed: int = 0,
                         sides: int = 6) -> tuple[float, float]:
    """Estimate P(sum of n_dice dice = target) by simulation: return (p_hat, standard_error)."""
    return monte_carlo_probability(
        lambda rng, n: rng.integers(1, sides + 1, size=(n, n_dice)),
        lambda rolls: rolls.sum(axis=1) == target,
        n_trials, seed)


def monte_carlo_error_study(n_trials_list: Sequence[int], n_repeats: int = 20, seed: int = 0,
                            n_dice: int = 2, target: int = 7) -> np.ndarray:
    """Return the root-mean-square error of the Monte Carlo dice-sum estimate for each sample size.

    For each N in ``n_trials_list`` the estimate is repeated ``n_repeats`` times with different seeds
    and compared with the exact probability from ``dice_sum_pmf``. The RMS error should fall as
    1/sqrt(N): a slope of -1/2 on log-log axes.
    """
    sums, probs = dice_sum_pmf(n_dice)
    p_exact = float(probs[sums == target][0]) if target in sums else 0.0
    rms = []
    for i, n in enumerate(n_trials_list):
        errs = [monte_carlo_dice_sum(n_dice, target, int(n), seed=seed + 1000 * i + r)[0] - p_exact
                for r in range(n_repeats)]
        rms.append(math.sqrt(float(np.mean(np.square(errs)))))
    return np.array(rms)


# ---------------------------------------------------------------- dice to dispersion

def random_walk_landings(n_layers: int, drift: float, n_trials: int, seed: int = 0) -> np.ndarray:
    """Return SYNTHETIC landing offsets (n_trials, 2) [m] of a payload drifting through wind layers.

    In each of ``n_layers`` layers the wind pushes the payload ``drift`` metres east or west (a
    fair coin) and, independently, ``drift`` metres north or south (another fair coin). The landing
    offset is the sum over the layers. Every step is one coin flip, which is why the exact
    distribution is binomial.
    """
    if n_layers < 1 or n_trials < 1 or drift < 0.0:
        raise ValueError("need n_layers >= 1, n_trials >= 1 and drift >= 0")
    rng = np.random.default_rng(seed)
    signs = rng.choice([-1.0, 1.0], size=(n_trials, n_layers, 2))
    return drift * signs.sum(axis=1)


def walk_endpoint_pmf(n_layers: int, drift: float) -> tuple[np.ndarray, np.ndarray]:
    """Return (positions, probabilities) of the one-axis endpoint of the coin-flip walk, exactly.

    With h heads (steps of +drift) out of n flips the endpoint is drift (2h - n), and h is binomial
    with p = 1/2: P(h) = C(n, h) / 2^n.
    """
    if n_layers < 1:
        raise ValueError("need n_layers >= 1")
    h = np.arange(n_layers + 1)
    probs = np.array([n_choose_k(n_layers, int(k)) for k in h], dtype=float) / 2.0 ** n_layers
    return drift * (2 * h - n_layers), probs


def probability_within_radius_exact(n_layers: int, drift: float, radius: float) -> float:
    """Return P(landing within ``radius`` of the target) for the coin-flip wind model, by exact counting.

    The east and north offsets are independent, so P(x, y) = P(x) P(y); sum over every grid point
    with x^2 + y^2 <= radius^2.
    """
    if radius < 0.0:
        raise ValueError("radius must be non-negative")
    pos, probs = walk_endpoint_pmf(n_layers, drift)
    x, y = np.meshgrid(pos, pos, indexing="ij")
    px, py = np.meshgrid(probs, probs, indexing="ij")
    inside = x ** 2 + y ** 2 <= radius ** 2 * (1.0 + 1e-12)
    return float(np.sum(px[inside] * py[inside]))


def probability_within_radius_mc(landings: np.ndarray, radius: float) -> tuple[float, float]:
    """Return (p_hat, standard_error) for the fraction of simulated landings within ``radius``."""
    landings = np.asarray(landings, dtype=float)
    if landings.ndim != 2 or landings.shape[1] != 2:
        raise ValueError("landings must have shape (n, 2)")
    r2 = np.sum(landings ** 2, axis=1)
    hits = r2 <= radius ** 2 * (1.0 + 1e-12)
    p_hat = float(np.count_nonzero(hits)) / landings.shape[0]
    return p_hat, proportion_standard_error(p_hat, landings.shape[0])


def gaussian_radius_probability(n_layers: int, drift: float, radius: float) -> float:
    """Return the continuous approximation 1 - exp(-R^2 / (2 sigma^2)) with sigma^2 = n_layers drift^2.

    This is the lesson-16 (Rayleigh) formula, quoted here only as the large-n comparison for
    ``probability_within_radius_exact``; each axis of the walk has variance n drift^2.
    """
    sigma2 = n_layers * drift ** 2
    if sigma2 <= 0.0:
        return 1.0 if radius >= 0.0 else 0.0
    return 1.0 - math.exp(-radius ** 2 / (2.0 * sigma2))


def radius_for_probability_exact(n_layers: int, drift: float, prob: float) -> float:
    """Return the smallest grid radius R such that P(within R) >= prob under the coin-flip model."""
    if not 0.0 <= prob <= 1.0:
        raise ValueError("prob must lie in [0, 1]")
    pos, probs = walk_endpoint_pmf(n_layers, drift)
    x, y = np.meshgrid(pos, pos, indexing="ij")
    px, py = np.meshgrid(probs, probs, indexing="ij")
    r = np.sqrt(x ** 2 + y ** 2).ravel()
    w = (px * py).ravel()
    order = np.argsort(r)
    cum = np.cumsum(w[order])
    idx = int(np.searchsorted(cum, prob * (1.0 - 1e-12)))
    return float(r[order][min(idx, len(r) - 1)])


# ---------------------------------------------------------------- the lesson's numbers

def main(out_dir: str | Path = ".") -> None:
    """Print the lesson's tables and write probability_fundamentals.png."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out_dir = Path(out_dir)
    np.set_printoptions(precision=4, suppress=True)

    print("== counting and the dice sample space ==")
    outcomes = enumerate_dice(2)
    p7 = event_probability(outcomes, lambda o: o.sum(axis=1) == 7)
    p_ge10 = event_probability(outcomes, lambda o: o.sum(axis=1) >= 10)
    p_double = event_probability(outcomes, lambda o: o[:, 0] == o[:, 1])
    p7_and_double = event_probability(outcomes, lambda o: (o.sum(axis=1) == 7) & (o[:, 0] == o[:, 1]))
    print(f"sample space of two dice: {outcomes.shape[0]} outcomes")
    print(f"P(sum = 7) = {p7:.6f} (= 6/36); P(sum >= 10) = {p_ge10:.6f} (= 6/36); P(double) = {p_double:.6f}")
    print(f"P(sum = 7 or double) = {addition_rule(p7, p_double, p7_and_double):.6f} (mutually exclusive: {p7_and_double})")
    p_one_six = event_probability(enumerate_dice(4), lambda o: np.any(o == 6, axis=1))
    print(f"P(at least one six in 4 rolls) = {p_one_six:.6f}; by complement 1 - (5/6)^4 = {1 - (5 / 6) ** 4:.6f}")
    print(f"C(10, 3) = {n_choose_k(10, 3)}, P(10, 3) = {permutations_count(10, 3)}, C(52, 5) = {n_choose_k(52, 5)}")

    print("\n== reliability from the multiplication and addition rules ==")
    stages = [0.995, 0.998, 0.990, 0.997, 0.999]
    print(f"five sequential flight events {stages}: P(all succeed) = {series_reliability(stages):.5f}")
    print(f"three IMUs at 0.98 each: any one working {parallel_reliability([0.98] * 3):.6f}, "
          f"2-of-3 voting {k_of_n_reliability(3, 2, 0.98):.6f}, all three {k_of_n_reliability(3, 3, 0.98):.6f}")
    for p in (0.90, 0.95, 0.98, 0.99):
        print(f"  p = {p:.2f}: single {p:.4f}, 2-of-3 {k_of_n_reliability(3, 2, p):.5f}, 3-of-5 {k_of_n_reliability(5, 3, p):.5f}")

    print("\n== the inspection tree (Bayes through a tree diagram) ==")
    tree = inspection_tree(prior_defect=0.02, detection_prob=0.90, false_alarm_prob=0.05)
    for key, val in tree.items():
        print(f"  {key:22s} {val:.5f}")
    print(f"posterior by bayes_posterior: {bayes_posterior([0.02, 0.98], [0.90, 0.05])}")

    print("\n== Monte Carlo against exact counting ==")
    for n in (100, 10_000, 1_000_000):
        p_hat, se = monte_carlo_dice_sum(2, 7, n, seed=15)
        print(f"  N = {n:>9d}: P(sum = 7) = {p_hat:.5f} +/- {se:.5f}  (exact 0.166667, error {p_hat - 1 / 6:+.5f})")
    ns = [100, 400, 1600, 6400, 25600]
    rms = monte_carlo_error_study(ns, n_repeats=20, seed=15)
    slope = np.polyfit(np.log(ns), np.log(rms), 1)[0]
    print(f"RMS error for N = {ns}: {rms}")
    print(f"log-log slope {slope:.3f} (1/sqrt(N) law predicts -0.5); predicted RMS {np.sqrt((1 / 6) * (5 / 6) / np.array(ns))}")

    print("\n== dice to dispersion: the coin-flip wind model (SYNTHETIC) ==")
    n_layers, drift, radius = 20, 15.0, 100.0
    sigma = drift * math.sqrt(n_layers)
    landings = random_walk_landings(n_layers, drift, 20_000, seed=2015)
    print(f"{n_layers} layers x {drift:.0f} m: per-axis standard deviation sqrt(n) d = {sigma:.2f} m")
    print(f"simulated: mean {landings.mean(axis=0)} m, std {landings.std(axis=0, ddof=1)} m")
    p_exact = probability_within_radius_exact(n_layers, drift, radius)
    p_mc, se_mc = probability_within_radius_mc(landings, radius)
    p_gauss = gaussian_radius_probability(n_layers, drift, radius)
    print(f"P(within {radius:.0f} m): exact {p_exact:.4f}, Monte Carlo {p_mc:.4f} +/- {se_mc:.4f}, "
          f"Gaussian approximation {p_gauss:.4f}")
    for prob in (0.5, 0.9, 0.99):
        print(f"  radius for {prob:.0%}: exact grid {radius_for_probability_exact(n_layers, drift, prob):.1f} m, "
              f"Gaussian {sigma * math.sqrt(-2 * math.log(1 - prob)):.1f} m")
    for n in (4, 10, 20, 50):
        print(f"  n = {n:2d}: P(within 1.5 sigma) exact {probability_within_radius_exact(n, drift, 1.5 * drift * math.sqrt(n)):.4f}, "
              f"Gaussian {gaussian_radius_probability(n, drift, 1.5 * drift * math.sqrt(n)):.4f}")

    fig, axes = plt.subplots(1, 3, figsize=(13, 3.9))
    sums, probs = dice_sum_pmf(2)
    rng = np.random.default_rng(15)
    rolls = rng.integers(1, 7, size=(2000, 2)).sum(axis=1)
    counts = np.array([np.count_nonzero(rolls == s) for s in sums]) / rolls.size
    axes[0].bar(sums - 0.2, probs, width=0.4, label="exact counting")
    axes[0].bar(sums + 0.2, counts, width=0.4, label="2000 simulated rolls")
    axes[0].set_xlabel("sum of two dice")
    axes[0].set_ylabel("probability")
    axes[0].legend()
    axes[1].loglog(ns, rms, "o-", label="RMS error (20 repeats)")
    axes[1].loglog(ns, np.sqrt((1 / 6) * (5 / 6) / np.array(ns)), "--", label=r"$\sqrt{p(1-p)/N}$")
    axes[1].set_xlabel("Monte Carlo trials N")
    axes[1].set_ylabel("error in P(sum = 7)")
    axes[1].legend()
    axes[1].grid(True, which="both", lw=0.4)
    axes[2].plot(landings[:2000, 0], landings[:2000, 1], ".", ms=2, alpha=0.5, label="2000 synthetic landings")
    th = np.linspace(0, 2 * np.pi, 200)
    axes[2].plot(radius * np.cos(th), radius * np.sin(th), "r-", label=f"recovery radius {radius:.0f} m")
    axes[2].set_aspect("equal")
    axes[2].set_xlabel("east offset [m]")
    axes[2].set_ylabel("north offset [m]")
    axes[2].legend(loc="upper right", fontsize=8)
    fig.suptitle("From dice to dispersion: counting, Monte Carlo error, coin-flip wind model (synthetic)")
    fig.tight_layout()
    fig.savefig(out_dir / "probability_fundamentals.png", dpi=150)
    print(f"saved {out_dir / 'probability_fundamentals.png'}")


if __name__ == "__main__":
    main()
